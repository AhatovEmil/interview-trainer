import 'package:flutter_test/flutter_test.dart';
import 'package:interview_trainer/core/plural.dart';

void main() {
  group('Русские числительные', () {
    test('единственное число', () {
      for (final int n in <int>[1, 21, 31, 101, 1001]) {
        expect(plural(n, 'вопрос', 'вопроса', 'вопросов'), 'вопрос', reason: 'n = $n');
      }
    });

    test('от двух до четырёх', () {
      for (final int n in <int>[2, 3, 4, 22, 33, 44, 102]) {
        expect(plural(n, 'вопрос', 'вопроса', 'вопросов'), 'вопроса', reason: 'n = $n');
      }
    });

    test('множественное число', () {
      for (final int n in <int>[0, 5, 9, 10, 20, 25, 100, 1000]) {
        expect(plural(n, 'вопрос', 'вопроса', 'вопросов'), 'вопросов', reason: 'n = $n');
      }
    });

    test('подростковые числа — исключение из правила', () {
      // 11–14 берут форму множественного, хотя оканчиваются на 1–4.
      for (final int n in <int>[11, 12, 13, 14, 111, 112, 113, 114]) {
        expect(plural(n, 'вопрос', 'вопроса', 'вопросов'), 'вопросов', reason: 'n = $n');
      }
    });

    test('число подставляется вместе с формой', () {
      expect(withPlural(1, 'направление', 'направления', 'направлений'), '1 направление');
      expect(withPlural(3, 'направление', 'направления', 'направлений'), '3 направления');
      expect(withPlural(6, 'направление', 'направления', 'направлений'), '6 направлений');
    });
  });
}
